// Flat array of 64 districts sorted by English name
export const BANGLADESH_DISTRICTS: { en: string; bn: string }[] = BANGLADESH_LOCATIONS.map((d) => ({
  en: d.en,
  bn: d.bn,
})).sort((a, b) => a.en.localeCompare(b.en));

// Lookup upazilas by district English or Bengali name
export function getUpazilasForDistrict(districtName: string): UpazilaItem[] {
  if (!districtName) return [];
  const normalized = districtName.trim().toLowerCase();
  const district = BANGLADESH_LOCATIONS.find(
    (d) => d.en.toLowerCase() === normalized || d.bn === districtName.trim()
  );
  return district ? district.upazilas : [];
}

// Format display location like "Mirpur, Dhaka" or "মিরপুর, ঢাকা"
export function formatLocation(district: string, upazila?: string, lang: 'en' | 'bn' = 'en'): string {
  if (!district) return '';
  const upazilas = getUpazilasForDistrict(district);
  const districtObj = BANGLADESH_LOCATIONS.find(
    (d) => d.en.toLowerCase() === district.toLowerCase() || d.bn === district
  );
  const displayDistrict = districtObj ? (lang === 'bn' ? districtObj.bn : districtObj.en) : district;

  if (!upazila) return displayDistrict;

  const upazilaObj = upazilas.find(
    (u) => u.en.toLowerCase() === upazila.toLowerCase() || u.bn === upazila
  );
  const displayUpazila = upazilaObj ? (lang === 'bn' ? upazilaObj.bn : upazilaObj.en) : upazila;

  return `${displayUpazila}, ${displayDistrict}`;
}
